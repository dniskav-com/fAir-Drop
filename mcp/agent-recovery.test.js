const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { AgentManager } = require('./agent-tools')
const { broker, until, sdkPeer } = require('./agent-test-helpers')
async function fixture(t) {
 const hub = await broker(), root = fs.mkdtempSync(path.join(os.tmpdir(),'fairdrop-recovery-'))
 const managers = []
 const make = projectDir => { const m = new AgentManager({url:hub.url,storeOptions:{root,projectDir},transportOptions:{relayOnly:true}}); managers.push(m);return m }
 const a = make(path.join(root,'a')),b=make(path.join(root,'b'))
 t.after(async()=>{managers.forEach(m=>m.shutdown());await hub.close();fs.rmSync(root,{recursive:true,force:true})})
 const created=await a.create({alias:'a'}),joined=await b.join({code:created.pairing_code,alias:'b'})
 const A=a.get(created.session_id),B=b.get(joined.session_id)
 await until(()=>A.state==='connected'&&B.state==='connected')
 return {hub,root,a,b,A,B,created,joined,make}
}
test('simultaneous first-use send/wait lazily resume one persisted session; queries do not reconnect',async t=>{
 const {hub,root,a,b,A,B,joined,make}=await fixture(t)
 b.shutdown();await until(()=>!hub.rooms.get(A.store.meta.code).guest)
 const restored=make(path.join(root,'b')),R=restored.get(joined.session_id)
 assert.equal(R.status().connection_state,'offline');assert.equal(R.status().needs_resume,true);R.inbox();assert.equal(hub.rooms.get(A.store.meta.code).guest,null)
 const wait=restored.wait(R.id,{timeout_s:5})
 const sent=await restored.send(R.id,{text:'after restart'})
 await until(()=>R.state==='connected'&&A.store.inbox.length===1)
 A.enqueue({text:'reply',reply_to:sent.message_id})
 assert.equal((await wait).messages[0].body.text,'reply')
 assert.equal(hub.captured.filter(m=>m.type==='join-room').length,2)
 assert.equal(R.store.outbox.length,1)
})
test('network loss reconnects automatically with bounded backoff and disconnect diagnostics',async t=>{
 const {A,B,hub}=await fixture(t)
 const ws=B.transport.ws;ws.terminate()
 await until(()=>B.transport.ws!==ws&&B.state==='connected')
 assert.equal(B.status().last_disconnect.reason,'signaling_closed');assert.equal(B.status().last_disconnect.websocket_code,1006)
 assert.equal(A.state,'connected');assert.ok(hub.captured.filter(m=>m.type==='join-room').length>=2)
})
test('offline wait returns an actionable result, and terminal authentication errors never auto-resume',async t=>{
 const {b,B}=await fixture(t)
 B.detach();const result=await B.waitMessage({timeout_s:1})
 assert.equal(result.outcome,'offline');assert.equal(result.needs_resume,true);assert.equal(result.retry_after_s,5)
 B.fail(new Error('authentication_failed: bad secret'))
 assert.equal(B.status().needs_resume,false)
 await assert.rejects(b.resume(B.id),/terminal error/)
})
test('a restarted real MCP process reconnects on first wait without a manual resume',async t=>{
 const {hub,root,a,A,joined,b}=await fixture(t)
 b.shutdown();await until(()=>!hub.rooms.get(A.store.meta.code).guest)
 const env={FAIRDROP_URL:hub.url,FAIRDROP_AGENT_DIR:root,FAIRDROP_PROJECT_DIR:path.join(root,'b'),FAIRDROP_AGENT_RELAY_ONLY:'1'}
 const peer=await sdkPeer(env);t.after(()=>peer.close())
 const offline=await peer.call('fairdrop_agent_status',{session_id:joined.session_id});assert.equal(offline.state,'offline')
 const wait=peer.call('fairdrop_agent_wait_message',{session_id:joined.session_id,timeout_s:5})
 await until(()=>A.state==='connected');A.enqueue({text:'recovered'})
 assert.equal((await wait).messages[0].body.text,'recovered')
 peer.transport._process.kill('SIGKILL');await until(()=>A.state==='reconnecting')
 const next=await sdkPeer(env);t.after(()=>next.close())
 const resumed=next.call('fairdrop_agent_wait_message',{session_id:joined.session_id,cursor:'1',timeout_s:5})
 await until(()=>A.state==='connected');A.enqueue({text:'after kill'})
 assert.equal((await resumed).messages[0].body.text,'after kill')
})

test('missing room fails queued delivery explicitly instead of claiming recovery is possible',async t=>{
 const {hub,root,a,b,A,B,joined,make}=await fixture(t)
 b.shutdown();await until(()=>!hub.rooms.get(A.store.meta.code).guest);hub.rooms.delete(A.store.meta.code)
 const restored=make(path.join(root,'b')),result=await restored.send(joined.session_id,{text:'not deliverable'})
 assert.equal(result.state,'failed');assert.equal(result.needs_resume,false);assert.equal(result.queued_offline,false)
 assert.match(result.error,/Terminal connection error/)
})
test('reconnect deadline is terminal with durable last-disconnect diagnostics',async t=>{
 const {A,B}=await fixture(t)
 B.detach();await until(()=>A.state==='reconnecting')
 A.transport.disconnectedAt=Date.now()-A.transport.reconnectMs-1;A.tick()
 assert.equal(A.state,'error');assert.match(A.error,/deadline expired/)
 assert.equal(A.status().needs_resume,false);assert.equal(A.status().last_disconnect.reason,'peer_disconnected')
})
